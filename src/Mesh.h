#ifndef MESH_H
#define MESH_H

#include "MeshTypes.h"

#include <iostream>
#include <map>
#include <utility>
#include <vector>

// Предикат: КЭ содержит все три заданных узла.
// Используется вместе с алгоритмом std::find_if.
class HasThreeNodes
{
public:
    // Что это: конструктор предиката, принимает номера трёх узлов.
    // Зачем:   запоминает эти номера в полях, чтобы потом при каждом вызове
    //          предиката проверять элементы именно на эти три узла.
    HasThreeNodes(int p_id1, int p_id2, int p_id3)
        : m_id1(p_id1), m_id2(p_id2), m_id3(p_id3)
    {}

    // Что это: оператор "вызова". Благодаря ему объект можно вызвать как функцию:
    //          predicate(element).
    // Зачем:   алгоритм std::find_if вызывает его для каждого элемента и спрашивает
    //          "подходит?". Возвращает true, если в элементе есть все три узла.
    bool operator()(const FiniteElement& p_element) const;

private:
    int m_id1;
    int m_id2;
    int m_id3;
};

// Класс сетки. Хранит узлы, объёмные КЭ (тетраэдры)
// и граничные КЭ (треугольники).
class Mesh
{
public:
    // Что это: конструктор пустой сетки - без узлов и элементов.
    // Зачем:   чтобы можно было объявить переменную "Mesh mesh;" и заполнить её позже.
    Mesh();

    // Что это: конструктор сетки из готовых списков узлов и элементов.
    // Зачем:   им пользуется загрузчик: прочитал всё из файла и одной строкой
    //          собрал из этого объект сетки.
    Mesh(const std::vector<Node>& p_nodes,
         const std::vector<FiniteElement>& p_elements,
         const std::vector<FiniteElement>& p_boundaryElements);

    // Что это: возвращает список всех узлов сетки.
    // Зачем:   чтобы снаружи узлы можно было прочитать (вывести, посчитать),
    //          но не изменить - ссылка константная.
    const std::vector<Node>& getNodes() const;

    // Что это: возвращает список всех объёмных КЭ (тетраэдров).
    // Зачем:   чтобы снаружи элементы можно было прочитать, но не изменить.
    const std::vector<FiniteElement>& getElements() const;

    // Что это: возвращает список всех граничных КЭ (треугольников на поверхности).
    // Зачем:   чтобы снаружи граничные элементы можно было прочитать, но не изменить.
    const std::vector<FiniteElement>& getBoundaryElements() const;

    // Что это: возвращает узел по его номеру (номера начинаются с 1).
    // Зачем:   чтобы быстро достать координаты узла, зная только его номер, -
    //          например, когда считаем середину ребра. Если узла с таким
    //          номером нет, бросает исключение BadIdException.
    const Node& getNode(int p_id) const;

    // Что это: ищет все тетраэдры, в которых есть три заданных узла.
    // Зачем:   три узла задают треугольную грань, и метод отвечает на вопрос
    //          "каким тетраэдрам принадлежит эта грань". Грань внутри детали
    //          общая у двух тетраэдров, грань на поверхности есть только у одного.
    //          Возвращает список номеров найденных тетраэдров.
    std::vector<int> findElementsByThreeNodes(int p_id1, int p_id2, int p_id3) const;

    // Что это: ищет все тетраэдры, у которых есть ребро между двумя заданными узлами.
    // Зачем:   отвечает на вопрос "какие тетраэдры сходятся на этом ребре".
    //          Возвращает список их номеров.
    std::vector<int> findElementsByEdge(int p_id1, int p_id2) const;

    // Что это: возвращает номера всех узлов, лежащих на заданной границе
    //          (грани детали), - каждый узел по одному разу.
    // Зачем:   к этим узлам при расчёте прикладывают закрепление или нагрузку,
    //          например "грань 12 закреплена".
    std::vector<int> getBoundaryNodeIds(int p_boundaryId) const;

    // Что это: возвращает номера всех тетраэдров с заданным номером области.
    // Зачем:   у каждого материала детали свой номер области, поэтому так можно
    //          выбрать все элементы одного материала.
    std::vector<int> getElementIdsByRegion(int p_regionId) const;

    // Что это: возвращает номера всех граничных треугольников на заданной границе.
    // Зачем:   чтобы получить все кусочки поверхности одной грани детали,
    //          например чтобы приложить к этой грани давление.
    std::vector<int> getBoundaryElementIds(int p_boundaryId) const;

    // Что это: для каждого узла находит его соседей - узлы, с которыми он
    //          соединён ребром. Элемент результата с индексом (id - 1)
    //          хранит соседей узла с номером id.
    // Зачем:   показывает, как узлы связаны между собой. При расчёте методом
    //          конечных элементов узел напрямую влияет только на своих соседей.
    std::vector<std::vector<int> > getNodeNeighbours() const;

    // Что это: добавляет новый узел в середину каждого ребра всех элементов.
    //          Сами элементы остаются теми же, но в них становится больше узлов:
    //          тетраэдр становится 10-узловым, треугольник - 6-узловым.
    // Зачем:   на таких элементах (их называют квадратичными) расчёт получается
    //          точнее. Узел на ребре, общем для нескольких элементов, создаётся
    //          только один раз.
    void splitEdges();

    // Что это: печатает один узел в заданный поток и переводит строку.
    // Зачем:   задание требует вывод в "заданный поток": можно передать
    //          std::cout (экран), std::cerr или открытый файл.
    void printNode(std::ostream& p_out, const Node& p_node) const;

    // Что это: печатает один конечный элемент в заданный поток и переводит строку.
    // Зачем:   то же, что printNode, только для элемента.
    void printElement(std::ostream& p_out, const FiniteElement& p_element) const;

private:
    // Число вершин у КЭ: 4 у тетраэдра, 3 у треугольника
    static const int VERTICES_IN_ELEMENT = 4;
    static const int VERTICES_IN_BOUNDARY_ELEMENT = 3;

    // Что это: составляет список рёбер элемента по количеству его вершин.
    //          Ребро записывается парой позиций вершин в списке узлов элемента.
    //          У тетраэдра (4 вершины) получается 6 рёбер, у треугольника - 3.
    // Зачем:   рёбра нужны в двух местах - при поиске соседей и при вставке узлов
    //          в середины рёбер. Чтобы не писать одинаковый код дважды,
    //          он вынесен в отдельный метод.
    static std::vector<std::pair<int, int> > makeEdges(int p_vertexCount);

    // Что это: вспомогательная часть splitEdges. Проходит по элементам из списка
    //          p_elements и в середину каждого их ребра добавляет узел.
    // Зачем:   splitEdges вызывает его дважды - для тетраэдров и для треугольников.
    //          Словарь p_createdNodes запоминает, на каких рёбрах узел уже создан,
    //          чтобы на общем ребре не появилось два разных узла.
    void addMiddleNodes(std::vector<FiniteElement>& p_elements,
                        int p_vertexCount,
                        std::map<std::pair<int, int>, int>& p_createdNodes);

    std::vector<Node> m_nodes;
    std::vector<FiniteElement> m_elements;          // тетраэдры
    std::vector<FiniteElement> m_boundaryElements;  // треугольники
};

#endif // MESH_H
